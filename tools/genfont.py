"""Generate src/uifont.h: anti-aliased glyph atlases for the frontend's text.

Cascadia Mono Bold (SIL Open Font License, see licenses/CascadiaMono.txt),
chars 32-126 plus the em dash (stored as code 1), at three sizes so text
stays crisp from small windows to 4K. Each glyph is an 8-bit coverage map in
a fixed cell, run-length encoded (0, n = n transparent pixels).
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

FONT = r"C:\Windows\Fonts\CascadiaMono.ttf"
SIZES = (24, 48, 96)
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "uifont.h")
CHARS = [(1, "\u2014")] + [(c, chr(c)) for c in range(32, 127)]

def rle(data):
    out, i = [], 0
    while i < len(data):
        if data[i] == 0:
            n = 0
            while i < len(data) and data[i] == 0 and n < 255:
                n += 1; i += 1
            out += [0, n]
        else:
            out.append(data[i]); i += 1
    return out

lines = ["/* generated by tools/genfont.py: Cascadia Mono Bold, chars 32-126 + em dash */",
         "#pragma once", "#include <stdint.h>", "",
         "typedef struct UiFontSize { int em, cellW, cellH, advance, capTop, capH; int dataLen; const uint8_t* data; } UiFontSize;",
         "#define UIFONT_SIZES %d" % len(SIZES),
         "#define UIFONT_GLYPHS %d   /* code 1 (em dash), then 32..126 */" % len(CHARS), ""]
sizes = []
for em in SIZES:
    font = ImageFont.truetype(FONT, em)
    try: font.set_variation_by_name("Bold")
    except Exception: pass
    asc, desc = font.getmetrics()
    cell_h = asc + desc
    adv = round(font.getlength("M"))
    cell_w = adv + 2
    cap = font.getbbox("H")          # (x0, y0, x1, y1) from the drawing origin
    data = []
    for code, ch in CHARS:
        img = Image.new("L", (cell_w, cell_h), 0)
        ImageDraw.Draw(img).text((1, 0), ch, fill=255, font=font)
        data += rle(img.tobytes())
    name = "uifont%d" % em
    lines.append("static const uint8_t %s[%d] = {" % (name, len(data)))
    for i in range(0, len(data), 40):
        lines.append(",".join(str(b) for b in data[i:i + 40]) + ",")
    lines.append("};")
    sizes.append("  { %d, %d, %d, %d, %d, %d, %d, %s }," % (em, cell_w, cell_h, adv, cap[1], cap[3] - cap[1], len(data), name))
    print(em, "cell", cell_w, "x", cell_h, "adv", adv, "cap", cap[1], cap[3] - cap[1], "bytes", len(data))
lines.append("static const UiFontSize uifontSizes[UIFONT_SIZES] = {")
lines += sizes
lines.append("};")
open(OUT, "w", encoding="ascii").write("\n".join(lines) + "\n")
print("wrote", OUT)
